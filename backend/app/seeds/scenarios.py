async def seed_scenarios(db: AsyncSession) -> int:
    """
    Insert all 20 scenarios if they don't exist yet (idempotent by slug).
    Returns the count of newly inserted rows.
    """
    inserted = 0
    for data in SCENARIOS:
        existing = await db.execute(
            select(Scenario).where(Scenario.slug == data["slug"])
        )
        if existing.scalar_one_or_none() is not None:
            logger.debug("seed_scenarios: slug=%s already exists, skipping", data["slug"])
            continue

        scenario = Scenario(
            slug=data["slug"],
            category=data["category"],
            title=data["title"],
            subtitle=data["subtitle"],
            situation=data["situation"],
            simulation_context=data["simulation_context"],
            recommended_persona=data["recommended_persona"],
            recommended_difficulty=data["recommended_difficulty"],
            tags=data["tags"],
            is_active=True,
            is_featured=data.get("is_featured", False),
        )
        db.add(scenario)
        inserted += 1
        logger.info("seed_scenarios: inserted slug=%s", data["slug"])

    await db.commit()
    logger.info("seed_scenarios: done, inserted=%d", inserted)
    return inserted
